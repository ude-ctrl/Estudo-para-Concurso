export function conceptFor(mission, text) {
  const t = text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
  const specialized = [
    ['gms', /gms|convers|minuto|segundo|20[°º]30/],
    ['latitude', /latitude|paralelo|equador|hemisfer/],
    ['longitude', /longitude|meridiano|greenwich/],
    ['lid', /linha.*data|\blid\b|cruzar/],
    ['area', /cm²|km²|quadrad|n²|areas? real|relacao.*areas|areas.*linear/],
    ['redimensionamento', /ampli|reduz|redimension|\bgrafica\b/],
    ['utm', /\butm\b|500.000|10.000.000|false/],
    ['semiologia', /nomina|ordina|bertin|variave|matiz|implant/],
    ['tematico', /coroplet|densidade|taxa|normaliz/],
    ['isolinhas', /isolin|isobar|isoterm|isoiet/],
    ['magnitude', /proporciona|fluxo|absolut/],
    ['relevo', /curva|decliv|perfil|equidistancia|montante/],
    ['espectro', /nir|infravermelho|assinatura|espectro/],
    ['classificacao', /classificac|validac|treinamento|confusao/],
    ['ndvi', /ndvi|falsa.cor|rgb/],
    ['datum', /sirgas|datum|sad69|rbmc|referencial/],
    ['topologia', /topolog|buffer|overlay|distancia|conect|adjacen/],
    ['operacoes-digitais', /geocodific|georreferenc|interpolac/],
  ];
  const candidates = concepts.filter((c) => c.mission === mission);
  for (const [id, re] of specialized)
    if (re.test(t) && candidates.some((c) => c.id === id)) return id;
  return candidates[0]?.id || 'critica';
}
